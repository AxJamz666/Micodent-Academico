-- MySQL's only ON UPDATE timestamp: preserve automatic update unless explicitly set.
CREATE FUNCTION touch_antecedentes_medicos() RETURNS trigger LANGUAGE plpgsql AS $touch$
BEGIN
  IF NEW IS DISTINCT FROM OLD AND NEW.actualizado_en IS NOT DISTINCT FROM OLD.actualizado_en THEN
    NEW.actualizado_en := statement_timestamp() AT TIME ZONE 'America/Lima';
  END IF;
  RETURN NEW;
END;
$touch$;
CREATE TRIGGER antecedentes_medicos_actualizado
BEFORE UPDATE ON antecedentes_medicos FOR EACH ROW EXECUTE FUNCTION touch_antecedentes_medicos();

